    private void btnApagarUsuarioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnApagarUsuarioActionPerformed
        try {
            Integer id = (Integer) modeloUsuario.getValueAt(usuarioTable.getSelectedRow(), 0);

            int linha = usuarioDao.apagar(id);
            if (linha > 0) {
                modeloUsuario.removeRow(usuarioTable.getSelectedRow());
                JOptionPane.showMessageDialog(this, "Item excluído com sucesso!");
            } else {
                JOptionPane.showMessageDialog(this, "Erro ao excluir.");
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Por favor, selecionar uma linha da tabela");
        }
    }//GEN-LAST:event_btnApagarUsuarioActionPerformed

