            DayWeek dia = (DayWeek) modeloTreino.getValueAt(treinoTable.getSelectedRow(), 2);
            Integer usuarioID = (Integer) modeloTreino.getValueAt(treinoTable.getSelectedRow(), 3);
            
            User usuario = usuarioDao.buscarPorId(usuarioID);
            
