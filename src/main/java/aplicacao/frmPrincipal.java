    private void btnMostrarTreinoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrarTreinoActionPerformed
        int linha = treinoTable.getSelectedRow();

        if (linha == -1) {
            JOptionPane.showMessageDialog(this,"Selecione um treino.");
            return;
        }
        
         int idTreino = (int) treinoTable.getValueAt(linha, 0);        
        
         Training treino = treinoDao.buscarPorId(idTreino);

         if (treino != null) {
            new frmMostrarTreino(this, true, treino).setVisible(true);   
         }    
    }//GEN-LAST:event_btnMostrarTreinoActionPerformed

