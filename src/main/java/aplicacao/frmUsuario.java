     private void cancelar() {
        int opcao = JOptionPane.showConfirmDialog(this, "Deseja realmente cancelar?", "Aviso", JOptionPane.YES_NO_OPTION);
        if (opcao == 0) {
            this.dispose();
        }
    }
     
    private void inserir() {
         User usuarioInserido = new User();
         
         usuarioInserido.setName(txtNome.getText());
         usuarioInserido.setAge(Integer.parseInt(txtIdade.getText()));
         usuarioInserido.setWeight(Double.parseDouble(txtPeso.getText()));
         usuarioInserido.setHeight(Double.parseDouble(txtAltura.getText()));
         usuarioInserido.setLevel(Level.valueOf((String) cmbNivel.getSelectedItem()));
         
         int linha = usuarioDao.inserir(usuarioInserido);
        if (linha > 0) {
            JOptionPane.showMessageDialog(this, "Usuário inserido com sucesso!");
        } else {
            JOptionPane.showMessageDialog(this, "Erro ao inserir Local.");
        } 
     }
     
     private void editar() {
        User usuarioEditado = new User();
        
         usuarioEditado.setId(usuario.getId());
         usuarioEditado.setName(txtNome.getText());
         usuarioEditado.setAge(Integer.parseInt(txtIdade.getText()));
         usuarioEditado.setWeight(Double.parseDouble(txtPeso.getText()));
         usuarioEditado.setHeight(Double.parseDouble(txtAltura.getText()));
         usuarioEditado.setLevel(Level.valueOf((String) cmbNivel.getSelectedItem()));

         int linha = usuarioDao.editar(usuarioEditado);
        if (linha > 0) {
            JOptionPane.showMessageDialog(this, "Usuário editado com sucesso!");
        } else {
            JOptionPane.showMessageDialog(this, "Erro ao editar Local.");
        } 
     
     }

