    private void btnOkActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnOkActionPerformed
        if (usuario != null) {
            try{
                editar();
                dispose();
            } catch (NumberFormatException e){
                JOptionPane.showMessageDialog(this, "Verifique os campos numéricos:\nIdade: não pode ter ponto flutuante (EX.: 4,0 OU 4.0)\nPeso e Altura: não pode utilizar ',' no ponto flutuante(EX.: 4,0)", "Erro", JOptionPane.ERROR_MESSAGE);
            }
        } else {
            try{
                inserir();
                dispose();
            } catch (NumberFormatException e){
                JOptionPane.showMessageDialog(this, "Verifique os campos numéricos:\nIdade: não pode ter ponto flutuante (EX.: 4,0 OU 4.0)\nPeso e Altura: não pode utilizar ',' no ponto flutuante (EX.: 4,0)", "Erro", JOptionPane.ERROR_MESSAGE);
            }   
        }
        
    }//GEN-LAST:event_btnOkActionPerformed

